"""Copies the library entries the store demo uses out of tool/game_library.json
into store_assets/demo/library_games.dart, so the demo app gets the games'
real rules without reading files at runtime.

Usage (from the repo root): python3 store_assets/demo/gen_library_games.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
ids = [
    # Les Bandits' catalog
    'skyjo', 'catan', 'mk', 'codenames', 'dixit', 'uno', 'petanque', 'timesup', '7_wonders', 'molkky',
    # Other library games (collections)
    'azul', 'splendor', 'aventuriers_du_rail', 'carcassonne', 'wingspan', 'kingdomino', 'just_one',
    'king_of_tokyo', 'six_qui_prend', 'love_letter',
]
library = json.loads((root / 'tool' / 'game_library.json').read_text(encoding='utf-8'))
subset = {i: library[i] for i in ids}
body = json.dumps(subset, ensure_ascii=False, separators=(',', ':'))
assert "'''" not in body
out = root / 'store_assets' / 'demo' / 'library_games.dart'
out.write_text(
    '// Generated by store_assets/demo/gen_library_games.py from tool/game_library.json.\n'
    '// Do not edit by hand.\n'
    '\n'
    '/// The shared-library games the store demo uses, keyed by library id.\n'
    "const kDemoLibraryJson = r'''" + body + "''';\n",
    encoding='utf-8',
)
print(f'{len(subset)} jeux -> {out.relative_to(root)} ({out.stat().st_size} octets)')
